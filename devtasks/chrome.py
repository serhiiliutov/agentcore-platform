"""A small Chrome DevTools Protocol driver, for capturing screenshots of the running page.

Why this exists rather than a folder of PNGs: the assignment asks for screenshots or a recording of
one run from start to finish, and a committed image with no way to produce it is an artefact nobody
can verify, refresh or argue with. So the screenshots are generated by a script that drives a real
browser against the real service, and the script is committed next to them.

There is no Playwright or Selenium here. `websockets` is already in the lock file (uvicorn's HTTP
extras pull it in), and everything else is the standard library, so the driver costs ~180 lines
instead of a browser-automation dependency with its own downloadable binaries. It is deliberately
narrow: open a page, evaluate JavaScript, wait for a condition, capture a PNG. It is not a general
automation library and should not grow into one.

Two details that are easy to get wrong and are handled here:

* **A CDP call is asynchronous and the socket carries events as well as replies.** Every reply is
  matched by `id` and everything else is discarded. Without that, the first `Page.navigate` would
  consume a `Page.frameNavigated` event as though it were its own answer and every later call
  would be off by one.
* **`Runtime.evaluate` returns a value only when asked.** `returnByValue` makes the result come
  back as JSON rather than a remote object handle, which is what a caller comparing against a
  boolean needs.
"""

from __future__ import annotations

import base64
import contextlib
import json
import os
import shutil
import socket
import subprocess
import tempfile
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.error import URLError
from urllib.request import Request, urlopen

from websockets.sync.client import connect

from devtasks.runner import TaskError

#: Where a CDP-capable browser usually lives, per platform. `CHROME_PATH` overrides all of them.
BROWSER_CANDIDATES: tuple[str, ...] = (
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe",
    r"C:\Program Files\Microsoft\Edge\Application\msedge.exe",
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium",
    "/usr/bin/chromium-browser",
)

#: How long to wait for the browser to open its debugging port. Generous: a cold start on Windows
#: with a fresh profile directory took ~2s when this was written, and a slow CI runner is slower.
LAUNCH_TIMEOUT_S = 30.0


def find_browser() -> str:
    """Resolve a CDP-capable browser, or explain what to install."""
    override = os.environ.get("CHROME_PATH")
    if override:
        if Path(override).is_file():
            return override
        raise TaskError(f"CHROME_PATH is set to {override!r}, which is not a file")

    for candidate in BROWSER_CANDIDATES:
        if Path(candidate).is_file():
            return candidate

    for name in ("google-chrome", "chromium", "chrome", "msedge"):
        found = shutil.which(name)
        if found:
            return found

    raise TaskError(
        "no CDP-capable browser found. Install Chrome or Edge, or point CHROME_PATH at one. "
        "The screenshots cannot be produced without a browser, and they are not faked when "
        "there is none."
    )


def _free_port() -> int:
    """A port nothing is listening on, so two captures cannot collide on a fixed one."""
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        return int(probe.getsockname()[1])


def _http_json(url: str, *, timeout: float = 2.0) -> Any:
    """GET a JSON endpoint. Used for the two HTTP endpoints CDP exposes before the socket."""
    with urlopen(Request(url), timeout=timeout) as response:
        return json.loads(response.read().decode())


@dataclass
class Chrome:
    """A running browser, its page target, and a socket to talk to it.

    Use as a context manager so a failure halfway through still closes the browser: a headless
    Chrome left behind holds its profile directory and, on Windows, occasionally the port.
    """

    websocket: Any
    process: subprocess.Popen[bytes]
    profile_dir: Path
    _next_id: int = 1
    _events: list[dict[str, Any]] = field(default_factory=list)

    # -- lifecycle -------------------------------------------------------------------------
    @classmethod
    def launch(
        cls,
        *,
        width: int = 1280,
        height: int = 900,
        browser: str | None = None,
    ) -> Chrome:
        """Start a headless browser and attach to its first page target."""
        executable = browser or find_browser()
        port = _free_port()
        profile_dir = Path(tempfile.mkdtemp(prefix="agentcore-shot-"))

        process = subprocess.Popen(
            [
                executable,
                "--headless=new",
                f"--remote-debugging-port={port}",
                "--disable-gpu",
                "--hide-scrollbars",
                "--no-first-run",
                "--no-default-browser-check",
                "--disable-extensions",
                f"--user-data-dir={profile_dir}",
                f"--window-size={width},{height}",
                "about:blank",
            ],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )

        target = cls._await_page_target(port, process)
        websocket = connect(target, max_size=None, open_timeout=LAUNCH_TIMEOUT_S)
        instance = cls(websocket=websocket, process=process, profile_dir=profile_dir)
        instance.call("Page.enable")
        instance.call("Runtime.enable")
        # A fixed viewport, so two runs produce the same picture and a layout that breaks at a
        # given width breaks visibly rather than depending on the window the capture ran in.
        instance.call(
            "Emulation.setDeviceMetricsOverride",
            {"width": width, "height": height, "deviceScaleFactor": 1, "mobile": False},
        )
        return instance

    @staticmethod
    def _await_page_target(port: int, process: subprocess.Popen[bytes]) -> str:
        """Poll until the browser offers a page target, or give up with the reason."""
        deadline = time.monotonic() + LAUNCH_TIMEOUT_S
        last_error = "no attempt made"
        while time.monotonic() < deadline:
            if process.poll() is not None:
                raise TaskError(
                    f"the browser exited immediately with code {process.returncode}. A headless "
                    f"browser needs no display, so this usually means the executable is not what "
                    f"it claims to be."
                )
            try:
                targets = _http_json(f"http://127.0.0.1:{port}/json/list")
            except (URLError, OSError, json.JSONDecodeError) as error:
                last_error = f"{type(error).__name__}: {error}"
                time.sleep(0.25)
                continue
            for target in targets:
                if target.get("type") == "page" and target.get("webSocketDebuggerUrl"):
                    return str(target["webSocketDebuggerUrl"])
            last_error = "the browser reported no page target"
            time.sleep(0.25)
        raise TaskError(
            f"the browser did not open a debugging port within {LAUNCH_TIMEOUT_S:.0f}s "
            f"(last error: {last_error})"
        )

    def close(self) -> None:
        """Detach, stop the browser, and remove its profile directory. Never raises."""
        # Best-effort throughout. This runs from `__exit__`, including on the path where the
        # caller is already handling a failure, so raising here would replace a useful error with
        # a teardown error.
        with contextlib.suppress(Exception):
            self.websocket.close()
        with contextlib.suppress(subprocess.TimeoutExpired):
            self.process.terminate()
            self.process.wait(timeout=10)
        if self.process.poll() is None:
            self.process.kill()
        shutil.rmtree(self.profile_dir, ignore_errors=True)

    def __enter__(self) -> Chrome:
        return self

    def __exit__(self, *_exc: object) -> None:
        self.close()

    # -- protocol --------------------------------------------------------------------------
    def call(
        self, method: str, params: dict[str, Any] | None = None, *, timeout: float = 30.0
    ) -> Any:
        """Send one CDP command and return its result, dropping any events in between.

        Returns `Any` on purpose: the result is whatever the browser chose to send back for that
        method, and inventing a shape here would be a claim about CDP this driver cannot support.
        Callers narrow it — `screenshot` reads `data`, `_await_page_target` never calls this.
        """
        message_id = self._next_id
        self._next_id += 1
        self.websocket.send(
            json.dumps({"id": message_id, "method": method, "params": params or {}})
        )

        deadline = time.monotonic() + timeout
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise TaskError(f"CDP call {method} timed out after {timeout:.0f}s")
            raw = self.websocket.recv(timeout=remaining)
            message = json.loads(raw)
            if message.get("id") != message_id:
                # An event, or a reply to something else. Kept rather than dropped so a caller
                # debugging the driver can see what the browser actually said.
                self._events.append(message)
                continue
            if "error" in message:
                raise TaskError(f"CDP call {method} failed: {message['error']}")
            return message.get("result", {})

    # -- page ------------------------------------------------------------------------------
    def goto(self, url: str, *, timeout: float = 30.0) -> None:
        """Navigate and wait until the document has finished loading."""
        self.call("Page.navigate", {"url": url}, timeout=timeout)
        self.wait_for(
            "document.readyState === 'complete'",
            timeout=timeout,
            description=f"{url} to finish loading",
        )

    def evaluate(self, expression: str, *, timeout: float = 30.0) -> Any:
        """Run JavaScript in the page and return its value.

        `awaitPromise` so an expression can await a fetch; `returnByValue` so the answer arrives
        as data rather than a handle the caller would have to resolve separately.
        """
        result = self.call(
            "Runtime.evaluate",
            {
                "expression": expression,
                "returnByValue": True,
                "awaitPromise": True,
                "userGesture": True,
            },
            timeout=timeout,
        )
        if "exceptionDetails" in result:
            detail = result["exceptionDetails"]
            text = detail.get("exception", {}).get("description") or detail.get("text")
            raise TaskError(f"the page raised while evaluating: {text}")
        return result.get("result", {}).get("value")

    def wait_for(
        self,
        expression: str,
        *,
        timeout: float = 30.0,
        interval: float = 0.2,
        description: str | None = None,
    ) -> Any:
        """Poll `expression` until it is truthy. The message names what was being waited for.

        Polling rather than listening for DOM events: the page is written with plain `fetch` and
        `addEventListener`, so "the app has finished" is observable as a condition on the DOM and
        there is no event name to subscribe to that would survive a change to the page.
        """
        what = description or expression
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            try:
                if self.evaluate(expression, timeout=max(1.0, deadline - time.monotonic())):
                    return True
            except TaskError:
                # A transient evaluation failure while the DOM is mid-update is normal; only the
                # deadline running out is a failure.
                pass
            time.sleep(interval)
        raise TaskError(f"timed out after {timeout:.0f}s waiting for {what}")

    def screenshot(self, path: Path) -> Path:
        """Capture the viewport as a PNG at `path`."""
        result = self.call("Page.captureScreenshot", {"format": "png"})
        data = base64.b64decode(result["data"])
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return path

    def set_value(self, selector: str, value: str) -> None:
        """Set a field's value and fire `input`/`change`, as typing would.

        Assigning `.value` alone is not enough: the page reads the field when the form is
        submitted, but a listener bound to `change` — the user/session fields have one — would
        never run, and a capture would then show a state the UI cannot actually reach.
        """
        self.evaluate(
            "(function () {"
            f"  var node = document.querySelector({json.dumps(selector)});"
            "  if (!node) throw new Error('no element matches ' + "
            f"{json.dumps(selector)});"
            f"  node.value = {json.dumps(value)};"
            "  node.dispatchEvent(new Event('input', { bubbles: true }));"
            "  node.dispatchEvent(new Event('change', { bubbles: true }));"
            "  return true;"
            "})()"
        )

    def click(self, selector: str) -> None:
        """Click the first element matching `selector`."""
        self.evaluate(
            "(function () {"
            f"  var node = document.querySelector({json.dumps(selector)});"
            f"  if (!node) throw new Error('no element matches ' + {json.dumps(selector)});"
            "  node.click();"
            "  return true;"
            "})()"
        )
